import assert from "node:assert/strict";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { flow, openProject, send, threadItem, toolShown, waitFor } from "./harness.ts";

flow("Kode-prosjekt: samme meny med høyreklikk og tastatur, filer, sti og riktig hoverkort", async (h) => {
  const { page } = h;
  writeFileSync(path.join(h.projectDir, "prosjekt.txt"), "Prosjektfil\n");
  const project = await openProject(h, "Kodeprosjekt");
  const thread = await h.createThread(project.id);
  const group = page.locator('.group[data-project="Kodeprosjekt"]');
  const head = group.locator(".group-head");
  await threadItem(page, thread.id).waitFor();
  // Picking the project ended on this row; leave it before testing a fresh hover.
  await page.mouse.move(700, 500);
  await head.hover();
  const card = page.getByTestId("hover-card-project");
  await card.getByText("1 tråd i Kode", { exact: true }).waitFor();
  await card.getByText(h.projectDir, { exact: true }).waitFor();
  await head.click({ button: "right" });
  const menu = page.getByRole("menu", { name: "Valg for Kodeprosjekt", exact: true });
  await menu.getByRole("menuitem", { name: "Fest prosjektet", exact: true }).waitFor();
  assert.equal(await card.count(), 0, "hoverkortet lukker når menyen åpnes");
  await page.keyboard.press("Enter");
  await waitFor(async () => (await h.api("GET", "/api/bootstrap")).projects.find((item: any) => item.id === project.id).pinned, "prosjektet festes med tastaturet");
  await head.hover();
  const trigger = group.getByRole("button", { name: "Valg for prosjektet", exact: true });
  await trigger.click();
  await menu.getByRole("menuitem", { name: "Kopier prosjektsti", exact: true }).click();
  await waitFor(async () => (await page.evaluate(() => navigator.clipboard.readText())) === h.projectDir, "kopiert sti stemmer");
  await head.hover();
  await trigger.click();
  await menu.getByRole("menuitem", { name: "Vis prosjektfiler", exact: true }).click();
  await toolShown(page, "Filer");
  await page.getByText("prosjekt.txt", { exact: true }).first().waitFor();
  await threadItem(page, thread.id).hover();
  const threadCard = page.getByTestId("hover-card-thread");
  await threadCard.getByText("Kode", { exact: true }).waitFor();
  await page.keyboard.press("Control+,");
  await page.getByRole("region", { name: "Innstillinger", exact: true }).waitFor();
  assert.equal(await threadCard.count(), 0, "hoverkort blir ikke liggende over innstillinger");
});

flow("Chat-prosjekter har egne kort og menyer, og Kode uten mappe merkes riktig", async (h) => {
  const { page } = h;
  const project = await h.api("POST", "/api/chat-projects", { name: "Samtaleprosjekt" });
  const thread = await h.createThread(null);
  await h.api("PATCH", `/api/threads/${thread.id}`, { chatProjectId: project.id });
  const group = page.locator('.group[data-chat-project="Samtaleprosjekt"]');
  await group.locator(".group-head").hover();
  const card = page.getByTestId("hover-card-chat-project");
  await card.getByText("1 chat i Chat", { exact: true }).waitFor();
  await card.getByText("Egne instruksjoner og minner for dette prosjektet.", { exact: true }).waitFor();
  await group.locator(".group-head").click({ button: "right" });
  const menu = page.getByRole("menu", { name: "Valg for Samtaleprosjekt", exact: true });
  await menu.getByRole("menuitem", { name: "Rediger prosjekt…", exact: true }).waitFor();
  assert.equal(await menu.getByRole("menuitem", { name: "Vis prosjektfiler", exact: true }).count(), 0);
  assert.equal(await menu.getByRole("menuitem", { name: "Kopier prosjektsti", exact: true }).count(), 0);
  await page.keyboard.press("Escape");
  await threadItem(page, thread.id).hover();
  await page.getByTestId("hover-card-thread").getByText("Chat · Samtaleprosjekt", { exact: true }).waitFor();
  await page.mouse.move(700, 600);
  const local = await h.api("POST", "/api/threads", { mode: "code", projectId: null });
  await h.api("PATCH", `/api/threads/${local.id}`, { title: "Lokal kodetråd" });
  await page.getByRole("button", { name: "Kode", exact: true }).first().click();
  await threadItem(page, local.id).hover();
  const localCard = page.getByTestId("hover-card-thread");
  await localCard.getByText("Kode · Denne datamaskinen", { exact: true }).waitFor();
  assert.equal(await localCard.getByText("Chat uten prosjekt", { exact: true }).count(), 0);
});

flow("manuell ulest beholdes for aktiv tråd og etter omlasting, og samtalen kan eksporteres lokalt", async (h) => {
  const { page } = h;
  await send(page, "hei");
  await waitFor(async () => (await h.api("GET", "/api/bootstrap")).threads.some((item: any) => item.lastStatus === "done"), "svaret er ferdig");
  const thread = (await h.api("GET", "/api/bootstrap")).threads[0];
  const item = threadItem(page, thread.id);
  await item.click({ button: "right" });
  const menu = page.locator('.context-menu[data-depth="0"]');
  await menu.getByRole("menuitem", { name: /^Merk som ulest/ }).click();
  await item.locator('.thread-dot[data-state="new"]').waitFor();
  await h.reload();
  await item.locator('.thread-dot[data-state="new"]').waitFor();
  await item.click({ button: "right" });
  await menu.getByRole("menuitem", { name: /^Merk som lest/ }).click();
  await waitFor(async () => (await item.locator('.thread-dot[data-state="new"]').count()) === 0, "eksplisitt lest nullstiller merket");
  await page.keyboard.press("Control+Shift+U");
  await item.locator('.thread-dot[data-state="new"]').waitFor();
  await item.locator(".thread-text").click();
  await waitFor(async () => (await item.locator('.thread-dot[data-state="new"]').count()) === 0, "gjenåpning merker tråden lest");
  await item.click({ button: "right" });
  const downloading = page.waitForEvent("download");
  await menu.getByRole("menuitem", { name: "Eksporter samtale…", exact: true }).click();
  const download = await downloading;
  assert.equal(download.suggestedFilename(), "hei.md");
  const saved = path.join(h.dataDir, "samtale.md");
  await download.saveAs(saved);
  const content = readFileSync(saved, "utf8");
  assert.match(content, /hei/);
  assert.match(content, /## Du/);
  assert.match(content, /## Svar/);
  const answer = (await h.events(thread.id)).flatMap(({ event }) => event.type === "text.delta" ? [event.text] : []).join("").trim().replace(/\n{3,}/g, "\n\n");
  assert.ok(answer.length > 100, "fixture har et helt strømmet svar");
  assert.ok(content.includes(answer), "eksporten inneholder hele det faktiske svaret, ikke bare en forventet demofrase");
});
