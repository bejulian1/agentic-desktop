import assert from "node:assert/strict";
import http from "node:http";
import { flow, openTool, pane, threadItem, waitFor } from "./harness.ts";

for (const mode of ["chat", "code"] as const) flow(`Oppstart i ${mode}: ny tom visning, historikk beholdes, reload og fortsett virker`, async (h) => {
  const { page } = h;
  if (mode === "code") await page.locator('.sidebar .mode-button').filter({ hasText: 'Kode' }).click();
  const thread = await h.api("POST", "/api/threads", { projectId: null, mode });
  await h.api("PATCH", `/api/threads/${thread.id}`, { title: "Lagret samtale" });
  await threadItem(page, thread.id).click();
  await pane(page, thread.id).waitFor();
  await waitFor(async () => !!(await h.api('GET', `/api/projects/${mode === 'code' ? 'local' : 'chat'}/layout`)).layout?.root?.threadId, 'layout lagret');
  await h.reload();
  await pane(page, thread.id).waitFor();
  await page.goto(h.origin);
  await page.locator('.app').waitFor();
  await page.locator('.pane-inner textarea').waitFor();
  assert.equal(await page.locator(`[data-thread-id="${thread.id}"]`).count(), 0);
  assert.equal(await page.locator('.pane-inner textarea').inputValue(), '');
  assert.equal(await threadItem(page, thread.id).isVisible(), true);
  assert.equal(await page.locator('.sidebar .mode-button[aria-pressed="true"]').innerText(), mode === 'code' ? 'Kode' : 'Chat');
  await threadItem(page, thread.id).click();
  await pane(page, thread.id).waitFor();
  await h.api('PATCH', '/api/settings', { startConversation: 'resume' });
  await page.goto(h.origin);
  await pane(page, thread.id).waitFor();
  await h.api('PATCH', '/api/settings', { startConversation: 'new', startMode: mode === 'code' ? 'chat' : 'code' });
  await page.goto(h.origin);
  await page.locator('.pane-inner textarea').waitFor();
  assert.equal(await page.locator('.pane-inner textarea').inputValue(), '');
  assert.equal((await h.api('GET', '/api/bootstrap')).threads.length, 1, 'oppstart lager ingen lagret tom tråd');
});

flow('Felles topprad: selvstendige terminal- og nettleserfaner, bevarte økter, tastatur og valgfri gruppering', async (h) => {
  const { page } = h;
  const fake = http.createServer((_req, res) => res.writeHead(200, {'content-type':'text/html; charset=utf-8'}).end('<title>Min prøveside</title><body style="background:rgb(0,160,0)">Dette er en prøve'));
  await new Promise<void>((resolve) => fake.listen(0, '127.0.0.1', resolve));
  try {
    await h.api('PATCH', '/api/settings', { cookieOffer:'never' });
    await page.locator('.sidebar .mode-button').filter({hasText:'Kode'}).click();
    await openTool(page, 'Terminal');
    await page.getByTestId('terminal').waitFor();
    const panel = page.locator('.right-panel');
    const row = panel.getByRole('tablist', {name:'Åpne verktøy'});
    await row.getByRole('tab', {name:'Terminal 1', exact:true}).waitFor();
    assert.equal(await panel.locator('.terminal-tabs').count(), 0);
    const firstId = await page.getByTestId('terminal').getAttribute('data-terminal-id');
    await panel.getByRole('button', {name:'Åpne verktøy', exact:true}).click();
    await panel.getByTestId('panel-home').getByRole('button', {name:'Ny terminal', exact:true}).click();
    await row.getByRole('tab', {name:'Terminal 2', exact:true, selected:true}).waitFor();
    assert.equal((await h.api('GET','/api/projects/local/terminals')).length, 2);
    await panel.getByRole('button', {name:'Åpne verktøy', exact:true}).click();
    await panel.getByTestId('panel-home').getByRole('button', {name:'Ny nettleserfane',exact:true}).click();
    const address = panel.getByRole('textbox', {name:'Adresse',exact:true});
    await address.fill(`http://127.0.0.1:${(fake.address() as any).port}`);
    await address.press('Enter');
    await row.getByRole('tab', {name:'Min prøveside',exact:true,selected:true}).waitFor();
    await waitFor(async () => page.getByTestId('browser-canvas').evaluate((el:HTMLCanvasElement) => el.width>0 && el.getContext('2d')!.getImageData(10,10,1,1).data[1]>100), 'nettleseren tegnes');
    await row.getByRole('tab', {name:'Terminal 1',exact:true}).click();
    await waitFor(async () => await page.getByTestId('terminal').getAttribute('data-terminal-id') === firstId, 'riktig terminal');
    assert.equal(await page.getByTestId('browser-panel').isVisible(), false);
    await row.getByRole('tab', {name:'Terminal 1',exact:true}).focus();
    await page.keyboard.press('End');
    await row.getByRole('tab', {name:'Min prøveside',selected:true}).waitFor();
    assert.equal(await row.getByRole('tab', {name:'Min prøveside'}).evaluate(el=>el===document.activeElement), true);
    await panel.getByRole('button', {name:'Åpne verktøy', exact:true}).click();
    await panel.getByTestId('panel-home').getByRole('button',{name:'Ny nettleserfane',exact:true}).click();
    await waitFor(async () => await row.getByRole('tab').count() === 4, 'to terminaler og to nettsider');
    await h.api('PATCH','/api/settings', {panelTabLayout:'grouped'});
    await row.getByRole('tab', {name:'Nettleser',exact:true}).waitFor();
    await panel.locator('.browser-tab').first().waitFor();
    await waitFor(async () => await panel.locator('.browser-tab').count() === 2, 'begge nettleserfaner gjenopprettet');
    await h.api('PATCH','/api/settings', {panelTabLayout:'unified'});
    await waitFor(async () => await row.getByRole('tab').count() === 4, 'fellesfaner tilbake');
    assert.equal((await h.api('GET','/api/projects/local/terminals')).length, 2);
    await row.getByRole('tab', {name:'Terminal 2',exact:true}).focus();
    await page.keyboard.press('Delete');
    await waitFor(async () => (await h.api('GET','/api/projects/local/terminals')).length===1,'bare valgt terminal lukkes');
    await h.api('PATCH','/api/settings',{panelButtons:'separate'});
    await page.getByTestId('stack-panel-browser').waitFor();
    await row.getByRole('tab', {name:'Min prøveside',exact:true}).click();
    assert.equal(await panel.locator('.stack-tabs .browser-tabs').count(), 0,'ikke dupliserte faner i stablet visning');
    await panel.getByRole('button',{name:'Lukk Min prøveside',exact:true}).click();
    await waitFor(async () => await row.getByRole('tab',{name:'Min prøveside',exact:true}).count()===0,'lukker én side');
    await panel.getByRole('button',{name:'Lukk Ny fane',exact:true}).click();
    await waitFor(async () => await row.locator('[data-panel-tab=browser]').count()===0,'siste nettleserfane lukker verktøyet');
    await panel.getByTestId('panel-home').filter({visible:true}).waitFor();
    assert.equal((await h.api('GET','/api/projects/local/terminals')).length,1,'stackbytte og nettleserlukking stopper ikke terminalen');
    await openTool(page,'Terminal');
    await row.getByRole('tab',{name:'Terminal 1',exact:true}).waitFor();
    await panel.getByRole('button',{name:'Lukk Terminal 1',exact:true}).click();
    await panel.getByTestId('panel-home').filter({visible:true}).waitFor();
  } finally { fake.closeAllConnections(); await new Promise<void>(resolve=>fake.close(()=>resolve())); }
});
