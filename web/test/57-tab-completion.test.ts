import assert from "node:assert/strict";
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { flow, openProject, openTool, pane, threadItem, waitFor, type Harness } from "./harness.ts";

async function seedHistory(h: Harness, threadId: string): Promise<void> {
  const finished = (await h.events(threadId)).filter((entry) => entry.event.type === "run.finished" && entry.event.status === "done").length;
  for (let index = 0; index < 2; index++) {
    await h.api("POST", `/api/threads/${threadId}/messages`, { text: index ? "Hallo" : "Hei" });
    await waitFor(async () => (await h.events(threadId)).filter((entry) => entry.event.type === "run.finished" && entry.event.status === "done").length > finished + index, "ekte demo-svar er ferdig");
  }
}

