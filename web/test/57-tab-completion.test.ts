flow("Grå promptfullføring er valgfri, følger linjebryting og Tab setter bare inn suffikset", async (h) => {
  const { page } = h;
  const requests: any[] = [];
  let sends = 0;
  const suffix = " og forklar hvordan endringen påvirker eksisterende funksjoner.\nTa også med relevante tester.";
  await page.route("**/api/prompt-completion", (route) => { requests.push(route.request().postDataJSON()); return route.fulfill({ json: { completion: suffix } }); });
  const field = page.getByLabel("Melding", { exact: true });
  await field.fill("Forklar denne funksjonen");
  await page.waitForTimeout(850);
  assert.equal(requests.length, 0, "av som standard");
  const thread = await h.createThread(null);
  await seedHistory(h, thread.id);
  await page.route("**/api/threads/*/messages", (route) => { sends++; return route.continue(); });
  await h.api("PATCH", "/api/settings", { promptAutocomplete: true });
  await h.reload();
  await threadItem(page, thread.id).locator(".thread-text").click();
  await page.setViewportSize({ width: 980, height: 800 });
  const prefix = "Forklar denne funksjonen grundig med et konkret eksempel som går over flere linjer i meldingsfeltet";
  await field.fill(prefix);
  const ghost = page.getByTestId("prompt-completion");
  await ghost.waitFor();
  assert.equal(await page.getByTestId("prompt-completion-suffix").textContent(), suffix);
  assert.equal(await field.inputValue(), prefix, "forslaget er ikke skrevet i utkastet ennå");
  assert.equal(requests.at(-1).mode, "chat");
  assert.equal(requests.at(-1).text, prefix);
  assert.ok(requests.at(-1).clientId);
  await waitFor(async () => await field.evaluate((el) => el.clientHeight > 50), "feltet gir plass til flere forslaglinjer");
  const layout = await ghost.evaluate((el) => {
    const textarea = el.parentElement!.querySelector("textarea")!;
    const mirrorStyle = getComputedStyle(el);
    const fieldStyle = getComputedStyle(textarea);
    const suffix = el.querySelector('[data-testid="prompt-completion-suffix"]')!;
    const range = document.createRange();
    range.selectNodeContents(suffix);
    return { font: mirrorStyle.font, fieldFont: fieldStyle.font, width: el.clientWidth, fieldWidth: textarea.clientWidth, lines: range.getClientRects().length, pointerEvents: mirrorStyle.pointerEvents, color: getComputedStyle(suffix).color, textColor: fieldStyle.color };
  });
  assert.equal(layout.font, layout.fieldFont);
  assert.equal(layout.width, layout.fieldWidth);
  assert.ok(layout.lines >= 2);
  assert.equal(layout.pointerEvents, "none");
  assert.notEqual(layout.color, layout.textColor);
  await page.screenshot({ path: "/tmp/ad-prompt-completion-preview.png" });
  await field.press("Tab");
  assert.equal(await field.inputValue(), prefix + suffix);
  assert.equal(await field.evaluate((el) => el === document.activeElement), true);
  assert.equal(sends, 0, "Tab sender aldri meldingen");
  assert.equal((await h.api("GET", "/api/bootstrap")).threads.length, 1, "fullføring oppretter ingen ekstra tråd");
  assert.equal((await h.events(thread.id)).filter((entry) => entry.event.type === "user.message").length, 2, "Tab legger ingen melding i samtalen");
});

flow("Promptforslag avbrytes ved ny tekst, markørflytting, IME, Escape og fokusbytte", async (h) => {
  const { page } = h;
  const thread = await h.createThread(null);
  await seedHistory(h, thread.id);
  await h.api("PATCH", "/api/settings", { promptAutocomplete: true });
  await h.reload();
  await threadItem(page, thread.id).locator(".thread-text").click();
  let release!: () => void;
  const pending = new Promise<void>((resolve) => { release = resolve; });
  const requests: string[] = [];
  await page.route("**/api/prompt-completion", async (route) => {
    const text = route.request().postDataJSON().text;
    requests.push(text);
    if (text === "Gammelt utkast") await pending;
    await route.fulfill({ json: { completion: text === "Gammelt utkast" ? " foreldet forslag" : " nytt forslag" } }).catch(() => undefined);
  });
  const field = page.getByLabel("Melding", { exact: true });
  const ghost = page.getByTestId("prompt-completion");
  await field.fill("Gammelt utkast");
  await waitFor(() => requests.includes("Gammelt utkast"), "første forespørsel venter");
  await field.fill("Nytt utkast");
  release();
  await ghost.waitFor();
  assert.equal(await page.getByTestId("prompt-completion-suffix").textContent(), " nytt forslag");
  await field.press("Control+a");
  await ghost.waitFor({ state: "detached" });
  await field.press("End");
  await ghost.waitFor();
  await field.press("Escape");
  await ghost.waitFor({ state: "detached" });
  const afterEscape = requests.length;
  await field.press("ArrowLeft");
  await field.press("End");
  await page.waitForTimeout(850);
  assert.equal(requests.length, afterEscape, "Escape avviser til neste tekstendring");
  await field.press("x");
  await ghost.waitFor();
  await field.press("ArrowLeft");
  await ghost.waitFor({ state: "detached" });
  await page.waitForTimeout(750);
  assert.equal(await ghost.count(), 0, "ingen forslag midt i teksten");
  await field.press("End");
  await ghost.waitFor();
  await field.press("Shift+Tab");
  await ghost.waitFor({ state: "detached" });
  assert.equal(await field.inputValue(), "Nytt utkastx");
  await field.focus();
  await field.dispatchEvent("compositionstart");
  await page.waitForTimeout(850);
  assert.equal(await ghost.count(), 0, "IME holder forslag tilbake");
  await field.dispatchEvent("compositionend");
  await ghost.waitFor();
  await h.api("PATCH", "/api/settings", { promptAutocomplete: false });
  await ghost.waitFor({ state: "detached" });
});

flow("Promptfullføring bruker bare den aktive trådens faktisk åpne kodefil og modell", async (h) => {
  const { page } = h;
  writeFileSync(path.join(h.projectDir, "kontekst.ts"), "export const testKontekst = 42;\n");
  const project = await openProject(h);
  const active = await h.createThread(project.id);
  const other = await h.createThread(project.id);
  await seedHistory(h, active.id);
  await seedHistory(h, other.id);
  await h.api("PATCH", "/api/settings", { promptAutocomplete: true });
  await h.reload();
  const requests: any[] = [];
  await page.route("**/api/prompt-completion", (route) => { requests.push(route.request().postDataJSON()); return route.fulfill({ json: { completion: " i den åpne filen" } }); });
  await threadItem(page, active.id).locator(".thread-text").click();
  await openTool(page, "Filer");
  await page.locator('.tree-item[data-path="kontekst.ts"]').click();
  await page.getByTestId("editor").getByText("testKontekst", { exact: false }).waitFor();
  const field = pane(page, active.id).getByLabel("Melding", { exact: true });
  await field.fill("Forklar konstanten");
  await page.getByTestId("prompt-completion").waitFor();
  assert.equal(requests.at(-1).filePath, "kontekst.ts");
  assert.equal(requests.at(-1).threadId, active.id);
  assert.equal(requests.at(-1).projectId, project.id);
  assert.equal(requests.at(-1).mode, "code");
  assert.equal(requests.at(-1).modelId, active.modelId ?? undefined);
  await threadItem(page, other.id).locator(".thread-text").click();
  await pane(page, other.id).getByLabel("Melding", { exact: true }).fill("Et annet utkast");
  await waitFor(() => requests.some((request) => request.threadId === other.id), "annen tråd har eget oppslag");
  assert.equal(requests.at(-1).filePath, undefined, "ny tråd arver ikke den forrige trådens filkontekst");
  await threadItem(page, active.id).locator(".thread-text").click();
  assert.equal(await field.inputValue(), "Forklar konstanten", "trådbytte bevarer utkastet");
});

flow("Innstillinger lagrer TAB-bryter og egen forslagsmodell uten å bytte samtalemodell", async (h) => {
  const { page } = h;
  const bootstrap = await h.api("GET", "/api/bootstrap");
  const model = await h.api("POST", "/api/models", { providerId: bootstrap.providers[0].id, name: "Egen forslagsmodell", model: "mock", contextWindow: 100_000 });
  await h.api("PATCH", "/api/settings", { defaultModelId: bootstrap.settings.defaultModelId });
  const thread = await h.createThread(null);
  await seedHistory(h, thread.id);
  await h.reload();
  await threadItem(page, thread.id).locator(".thread-text").click();
  await page.keyboard.press("Control+,");
  const settings = page.getByRole("region", { name: "Innstillinger" });
  const toggle = settings.getByRole("switch", { name: /^Autofullfør meldinger med TAB/ });
  await toggle.waitFor();
  assert.equal(await toggle.isChecked(), false);
  await toggle.click();
  await settings.getByRole("button", { name: "Modell til autofullføring", exact: true }).click();
  await page.getByRole("menuitemradio", { name: /Egen forslagsmodell/ }).click();
  await waitFor(async () => (await h.api("GET", "/api/bootstrap")).settings.promptAutocompleteModelId === model.id, "egen modell er lagret");
  assert.equal((await h.api("GET", "/api/bootstrap")).settings.defaultModelId, bootstrap.settings.defaultModelId);
  await h.reload();
  assert.equal((await h.api("GET", "/api/bootstrap")).settings.promptAutocomplete, true);
  await page.keyboard.press("Control+,");
  await settings.getByRole("button", { name: "Modell til autofullføring", exact: true }).filter({ hasText: "Egen forslagsmodell" }).waitFor();
  await page.keyboard.press("Escape");
  const requests: any[] = [];
  await page.route("**/api/prompt-completion", (route) => { requests.push(route.request().postDataJSON()); return route.fulfill({ json: { completion: " forslag" } }); });
  const field = page.getByLabel("Melding", { exact: true });
  await field.fill("Skriv et utkast");
  await page.getByTestId("prompt-completion").waitFor();
  assert.equal(requests.at(-1).modelId, model.id);
  await h.api("PATCH", "/api/settings", { promptAutocompleteModelId: null });
  await page.getByTestId("prompt-completion").waitFor({ state: "detached" });
  await waitFor(() => requests.length >= 2, "nytt forslag bruker samtalens modell");
  assert.notEqual(requests.at(-1).modelId, model.id);
});

flow("Promptforslag begynner først ved tredje melding etter to ferdige brukerturer", async (h) => {
  const { page } = h;
  await h.api("PATCH", "/api/settings", { promptAutocomplete: true });
  await h.reload();
  const requests: any[] = [];
  await page.route("**/api/prompt-completion", (route) => { requests.push(route.request().postDataJSON()); return route.fulfill({ json: { completion: " med relevant historikk" } }); });
  const field = page.getByLabel("Melding", { exact: true });
  await field.fill("Hei");
  await page.waitForTimeout(850);
  assert.equal(requests.length, 0, "første melding har ingen forslag");
  await field.press("Enter");
  await page.locator(".row-text").first().waitFor();
  const threadId = (await page.locator(".pane-inner.focused").getAttribute("data-thread-id"))!;
  await waitFor(async () => (await h.events(threadId)).filter((entry) => entry.event.type === "run.finished" && entry.event.status === "done").length === 1, "første svar er ferdig");
  await field.fill("Hallo");
  await page.waitForTimeout(850);
  assert.equal(requests.length, 0, "andre melding har heller ingen forslag");
  await field.press("Enter");
  await waitFor(async () => (await h.events(threadId)).filter((entry) => entry.event.type === "run.finished" && entry.event.status === "done").length === 2, "andre svar er ferdig");
  await field.fill("Forklar videre");
  await page.getByTestId("prompt-completion").waitFor();
  assert.equal(requests.at(-1).threadId, threadId);
  assert.equal(requests.at(-1).text, "Forklar videre");
  assert.equal((await h.events(threadId)).filter((entry) => entry.event.type === "user.message").length, 2);
});
