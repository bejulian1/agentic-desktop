import assert from "node:assert/strict";
import { flow, pane, send, waitFor } from "./harness.ts";

flow("Chat bevarer synlig svar, redigering og vedlegg ved feil, og lar brukeren prøve igjen", async (h) => {
  const { page } = h;
  await page.getByTestId("text-file-input").setInputFiles({ name: "notat.txt", mimeType: "text/plain", buffer: Buffer.from("Et faktisk tekstvedlegg\n") });
  await page.locator(".chip", { hasText: "notat.txt" }).waitFor();
  await send(page, "hva står i vedleggene");
  const answer = page.locator(".row-text").first();
  await answer.waitFor();
  const id = (await page.locator(".pane-inner.focused").getAttribute("data-thread-id"))!;
  await waitFor(async () => (await h.events(id)).some((event) => event.event.type === "run.finished"), "svaret er ferdig");
  const before = await h.events(id);
  const original = await answer.innerText();
  h.allow(/status of 503/);
  let fails = true;
  await page.route(`**/api/threads/${id}/rewind`, (route) => fails ? route.fulfill({ status: 503, json: { error: "Test: chatten kunne ikke sendes på nytt" } }) : route.continue());
  const user = page.locator(".row-user").first();
  await user.hover();
  await user.getByRole("button", { name: "Rediger", exact: true }).click();
  const editor = page.getByLabel("Rediger meldingen", { exact: true });
  await editor.fill("hva står i vedleggene nå");
  await page.getByRole("button", { name: "Lagre og send", exact: true }).click();
  await page.locator(".toast.error", { hasText: "Test: chatten kunne ikke sendes på nytt" }).last().waitFor();
  assert.equal(await editor.inputValue(), "hva står i vedleggene nå", "utkastet beholdes ved mislykket redigering");
  assert.deepEqual(await h.events(id), before, "mislykket forespørsel endrer ingen historikk");
  assert.equal(await answer.innerText(), original);
  assert.ok(await answer.evaluate((element) => Number(getComputedStyle(element).opacity) > 0.9), "det tidligere svaret er fortsatt synlig etter mislykket falming");
  await page.getByRole("button", { name: "Avbryt", exact: true }).click();
  await user.hover();
  await user.getByRole("button", { name: "Rediger", exact: true }).click();
  await editor.fill("hva står i vedleggene etter nytt forsøk");
  fails = false;
  await page.getByRole("button", { name: "Lagre og send", exact: true }).click();
  await page.getByTestId("user-edit").waitFor({ state: "detached" });
  await waitFor(async () => (await page.locator(".pane-dot.running").count()) === 0, "redigeringen er ferdig");
  const updated = await h.events(id);
  const message = updated.find((event) => event.event.type === "user.message")!;
  assert.equal(message.event.type, "user.message");
  if (message.event.type !== "user.message") throw new Error("Meldingen mangler");
  assert.equal(message.event.text, "hva står i vedleggene etter nytt forsøk");
  assert.equal(message.event.attachments?.[0].label, "notat.txt");
  assert.equal(await answer.count(), 1);
  await answer.hover();
  fails = true;
  await page.locator('.msg [data-msg-action="regenerate"]').click();
  await page.locator(".toast.error", { hasText: "Test: chatten kunne ikke sendes på nytt" }).last().waitFor();
  await waitFor(async () => (await page.locator('[data-msg-action="regenerate"]').getAttribute("aria-disabled")) === null, "nytt svar kan prøves igjen etter feilen");
  assert.ok(await answer.evaluate((element) => Number(getComputedStyle(element).opacity) > 0.9));
  fails = false;
  await page.locator('[data-msg-action="regenerate"]').click();
  await waitFor(async () => (await h.events(id)).some((event) => event.event.type === "run.started" && event.at > Math.max(...updated.map((old) => old.at))), "nytt svar startet");
  await waitFor(async () => (await page.locator(".pane-dot.running").count()) === 0, "nytt svar er ferdig");
  assert.equal(await pane(page, id).locator(".row-text").count(), 1);
  for (const testId of ["permission-button", "goal-composer", "changes-card", "now-line", "turn-summary"]) assert.equal(await page.getByTestId(testId).count(), 0);
  assert.equal(await page.locator(".row-work").count(), 0);
});

flow("Chat skjuler Kode-mål og plan, og midlertidig chat viser minnegrensen, stopper og slettes ved lukking", async (h) => {
  const { page } = h;
  await page.getByLabel("Melding", { exact: true }).fill("!Hei, dette er vanlig Chat-tekst");
  assert.equal(await page.getByTestId("composer-menu").count(), 0, "Chat tolker ikke utropstegn som shell");
  await page.getByLabel("Melding", { exact: true }).press("Enter");
  await page.locator(".row-text").first().waitFor();
  const id = (await page.locator(".pane-inner.focused").getAttribute("data-thread-id"))!;
  await waitFor(async () => (await h.events(id)).some((event) => event.event.type === "run.finished"), "vanlig Chat er ferdig");
  const before = await h.events(id);
  assert.ok(before.some((entry) => entry.event.type === "user.message" && entry.event.text.startsWith("!Hei")));
  assert.ok(before.every((entry) => entry.event.type !== "tool.started"));
  const field = page.getByLabel("Melding", { exact: true });
  await field.fill("/");
  const menu = page.getByTestId("composer-menu");
  await menu.waitFor();
  assert.equal(await menu.locator(".menu-name", { hasText: /^\/(plan|goal)$/ }).count(), 0);
  await field.press("Escape");
  for (const command of ["/plan", "/goal Et mål som ikke skal opprettes i Chat"]) {
    await send(page, command);
    await page.locator(".toast", { hasText: `/${command.split("/")[1].split(" ")[0]} er bare tilgjengelig i Kode.` }).waitFor();
  }
  const stored = (await h.api("GET", "/api/bootstrap")).threads.find((thread: any) => thread.id === id);
  assert.equal(stored.planMode, false);
  assert.equal(stored.goal, null);
  assert.deepEqual(await h.events(id), before);
  await h.api("PUT", "/api/chat-personal", { memories: true, autoMemory: true });
  await h.api("POST", "/api/chat-personal/memories", { text: "Et vanlig lagret Chat-minne" });
  const memories = (await h.api("GET", "/api/chat-personal")).memories;
  await page.keyboard.press("Control+j");
  await page.getByRole("button", { name: "Midlertidig chat", exact: true }).click();
  await page.getByRole("heading", { name: "Denne chatten beholdes midlertidig", exact: true }).waitFor();
  const temp = (await page.locator(".pane-inner.focused").getAttribute("data-thread-id"))!;
  await page.getByTestId("chat-tools-button").click();
  const memory = page.getByRole("menuitemcheckbox", { name: /^Minne/ });
  assert.equal(await memory.getAttribute("aria-checked"), "false");
  assert.equal(await memory.getAttribute("aria-disabled"), "true");
  assert.equal(await memory.getAttribute("title"), "Midlertidige chatter bruker ikke lagrede minner.");
  await page.keyboard.press("Escape");
  await page.getByRole("button", { name: "Legg ved", exact: true }).click();
  assert.equal(await page.getByRole("menuitem", { name: "Legg til mappe", exact: true }).count(), 0, "Chat gir ikke prosjektmapper til modellen");
  await page.keyboard.press("Escape");
  await send(page, "lang strøm 20000 rolig");
  await waitFor(async () => (await pane(page, temp).locator(".row-text").innerText()).length > 150, "svaret strømmer i Chat");
  await page.getByTestId("temp-banner").getByText("Midlertidig chat. Vises ikke i historikken, og slettes når du lukker den.", { exact: true }).waitFor();
  for (const testId of ["permission-button", "goal-composer", "changes-card", "now-line", "turn-summary"]) assert.equal(await page.getByTestId(testId).count(), 0);
  assert.equal(await page.locator(".row-work").count(), 0);
  await pane(page, temp).getByRole("button", { name: "Stopp", exact: true }).click();
  await waitFor(async () => (await h.events(temp)).some((event) => event.event.type === "run.finished" && event.event.status === "stopped"), "Stopp avslutter den faktiske Chat-strømmen");
  await page.locator(".sidebar .mode-button", { hasText: "Kode" }).click();
  await page.locator(".sidebar .mode-button", { hasText: "Chat" }).click();
  await page.getByTestId("temp-banner").waitFor();
  assert.ok((await h.api("GET", "/api/bootstrap")).threads.some((thread: any) => thread.id === temp), "modusbytte lukker ikke midlertidig chat");
  assert.equal((await h.api("GET", "/api/threads/search?q=lang")).length, 0);
  await page.keyboard.press("Control+j");
  await waitFor(async () => !(await h.api("GET", "/api/bootstrap")).threads.some((thread: any) => thread.id === temp), "midlertidig chat slettes etter lukking", 10_000);
  assert.deepEqual((await h.api("GET", "/api/chat-personal")).memories, memories, "midlertidig chat endrer ingen lagrede minner");
});
