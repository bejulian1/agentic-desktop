import assert from "node:assert/strict";
import { mkdirSync } from "node:fs";
import path from "node:path";
import { flow, openProject, openTool, toolShown, waitFor } from "./harness.ts";

flow("Verktøyfaner: felles pluss viser velgeren uten å opprette terminaler eller nettleserfaner", async (h) => {
  const { page } = h;
  await h.api("PATCH", "/api/settings", { panelTabLayout: "grouped" });
  const project = await openProject(h, "Verktøyprosjekt");
  await openTool(page, "Terminal");
  const panel = page.locator(".right-panel");
  const tabs = panel.getByRole("tablist", { name: "Åpne verktøy" });
  await page.getByTestId("terminal").waitFor();
  await waitFor(async () => (await h.api("GET", `/api/projects/${project.id}/terminals`)).length === 1, "én terminal");
  assert.equal(await tabs.locator("[data-panel-tab]").count(), 1, "bare verktøyet som ble åpnet har fane");
  assert.equal(await panel.getByRole("button", { name: "Ny terminal", exact: true }).innerText(), "Ny terminal");
  assert.equal(await page.getByTestId("panel-switch").count(), 0, "ingen ekstra Terminal-nedtrekksrad");
  await page.evaluate(() => {
    const send = WebSocket.prototype.send;
    (window as any).__panelCommands = [];
    WebSocket.prototype.send = function (data) {
      try { (window as any).__panelCommands.push(JSON.parse(String(data))); } catch { /* non-JSON transport */ }
      return send.call(this, data);
    };
  });
  await panel.getByRole("button", { name: "Åpne verktøy", exact: true }).click();
  await panel.getByTestId("panel-home").waitFor();
  assert.equal((await h.api("GET", `/api/projects/${project.id}/terminals`)).length, 1);
  assert.deepEqual(await page.evaluate(() => (window as any).__panelCommands.filter((m: any) => m.type === "browser.open" || m.type === "terminal.open")), [], "+ oppretter bare velgervisningen");
  await tabs.getByRole("tab", { name: "Terminal", exact: true }).click();
  await page.getByTestId("terminal").waitFor();
  assert.equal((await h.api("GET", `/api/projects/${project.id}/terminals`)).length, 1, "gjenåpning bruker den eksisterende terminalen");
  await panel.getByRole("button", { name: "Ny terminal", exact: true }).click();
  await waitFor(async () => (await h.api("GET", `/api/projects/${project.id}/terminals`)).length === 2, "den tydelige terminalhandlingen oppretter en terminal");
  await openTool(page, "Nettleser");
  await panel.locator(".browser-tab").first().waitFor();
  const browserTabs = await panel.locator(".browser-tab").evaluateAll((elements) => elements.map((el) => el.getAttribute("data-tab")));
  const browserRequests = () => page.evaluate(() => (window as any).__panelCommands.filter((m: any) => m.type === "browser.open").length);
  const before = await browserRequests();
  await panel.getByRole("button", { name: "Åpne verktøy", exact: true }).click();
  await panel.getByTestId("panel-home").waitFor();
  assert.equal(await browserRequests(), before, "+ sender ingen browser.open");
  await tabs.getByRole("tab", { name: "Nettleser", exact: true }).click();
  await panel.locator(".browser-tab").first().waitFor();
  assert.deepEqual(await panel.locator(".browser-tab").evaluateAll((elements) => elements.map((el) => el.getAttribute("data-tab"))), browserTabs, "retur fra velgeren beholder de samme nettleserfanene");
  await panel.getByRole("button", { name: "Lukk verktøyet Nettleser" }).click();
  await tabs.getByRole("tab", { name: "Terminal", selected: true, exact: true }).waitFor();
  await panel.getByRole("button", { name: "Lukk verktøyet Terminal" }).click();
  await panel.getByTestId("panel-home").waitFor();
  assert.equal(await tabs.locator("[data-panel-tab]").count(), 0);
  assert.equal(await panel.getByRole("button", { name: "Åpne verktøy", exact: true }).isVisible(), true);
});

flow("Verktøyfaner: tastatur, startinnstillinger og separate prosjektscope", async (h) => {
  const { page } = h;
  await h.api("PATCH", "/api/settings", { panelTabLayout: "grouped" });
  const project = await openProject(h, "Første verktøyprosjekt");
  await h.api("PATCH", "/api/settings", { panelStart: "tabs" });
  await openTool(page, "Filer");
  await openTool(page, "Diff");
  const panel = page.locator(".right-panel");
  const tabs = panel.getByRole("tablist", { name: "Åpne verktøy" });
  await tabs.getByRole("tab", { name: "Diff", exact: true }).focus();
  await page.keyboard.press("ArrowLeft");
  await tabs.getByRole("tab", { name: "Filer", selected: true, exact: true }).waitFor();
  assert.equal(await tabs.getByRole("tab", { name: "Filer", exact: true }).evaluate((el) => el === document.activeElement), true);
  await page.keyboard.press("Delete");
  assert.equal(await tabs.getByRole("tab", { name: "Filer", exact: true }).count(), 0);
  await panel.getByRole("button", { name: "Åpne verktøy", exact: true }).click();
  await panel.getByTestId("panel-home").waitFor();
  await h.api("PATCH", "/api/settings", { panelStart: "tools" });
  await panel.getByTestId("panel-home").waitFor();
  await openTool(page, "Filer");
  await toolShown(page, "Filer");
  const secondPath = path.join(h.home, "andre-verktøyprosjekt");
  mkdirSync(secondPath);
  await h.api("POST", "/api/projects", { name: "Andre verktøyprosjekt", path: secondPath });
  await page.locator('.group[data-project="Andre verktøyprosjekt"] .group-title').first().click();
  await panel.getByTestId("panel-home").waitFor();
  assert.equal(await tabs.locator("[data-panel-tab]").count(), 0, "et annet prosjekt starter med sitt eget fanesett");
  await openTool(page, "Terminal");
  await page.getByTestId("terminal").waitFor();
  await page.locator('.group[data-project="Første verktøyprosjekt"] .group-title').first().click();
  await tabs.getByRole("tab", { name: "Filer", selected: true, exact: true }).waitFor();
  assert.equal(await tabs.getByRole("tab", { name: "Terminal", exact: true }).count(), 0);
  assert.equal((await h.api("GET", `/api/projects/${project.id}/terminals`)).length, 0, "den andre terminalen ble ikke startet i første prosjekt");
});

flow("Verktøyfaner i stack: pluss beholder panelene og siste lukk viser velgeren", async (h) => {
  const { page } = h;
  await h.api("PATCH", "/api/settings", { panelTabLayout: "grouped" });
  await openProject(h, "Stablede verktøy");
  await h.api("PATCH", "/api/settings", { panelButtons: "separate", panelStart: "tools" });
  await openTool(page, "Diff");
  const panel = page.locator(".right-panel");
  const changes = page.getByTestId("stack-panel-changes");
  await changes.waitFor();
  await changes.evaluate((el) => el.setAttribute("data-mount-marker", "behold"));
  await panel.getByRole("button", { name: "Åpne verktøy", exact: true }).click();
  await panel.getByTestId("panel-home").waitFor();
  assert.equal(await changes.isVisible(), false);
  await panel.getByRole("tab", { name: "Diff", exact: true }).click();
  await changes.waitFor({ state: "visible" });
  assert.equal(await changes.getAttribute("data-mount-marker"), "behold", "velgeren demonterer ikke stackverktøy");
  await h.reload();
  await changes.waitFor({ state: "visible" });
  assert.equal(await panel.getByTestId("panel-home").count(), 0, "et lagret stackoppsett åpnes synlig etter reload");
  await panel.getByRole("button", { name: "Åpne verktøy", exact: true }).click();
  await panel.getByTestId("panel-home").waitFor();
  assert.equal(await changes.isVisible(), false, "et eksplisitt plussvalg kan fortsatt skjule det gjenopprettede oppsettet");
  await panel.getByRole("tab", { name: "Diff", exact: true }).click();
  await panel.getByRole("button", { name: "Lukk verktøyet Diff", exact: true }).click();
  await panel.getByTestId("panel-home").waitFor();
  assert.equal(await panel.locator("[data-panel-tab]").count(), 0);
  assert.equal(await panel.isVisible(), true, "siste lukk skjuler ikke panelet");
});

flow("Verktøyfaner: terminalen beholder fanefokus og topbar-lukk rydder stack og fanesett", async (h) => {
  const { page } = h;
  await h.api("PATCH", "/api/settings", { panelTabLayout: "grouped" });
  await openProject(h, "Fokus og lukk");
  await openTool(page, "Terminal");
  await page.getByTestId("terminal").waitFor();
  await openTool(page, "Diff");
  const panel = page.locator(".right-panel");
  const tabs = panel.getByRole("tablist", { name: "Åpne verktøy" });
  await tabs.getByRole("tab", { name: "Diff", exact: true }).focus();
  await page.keyboard.press("ArrowLeft");
  await page.getByTestId("terminal").waitFor();
  assert.equal(await tabs.getByRole("tab", { name: "Terminal", selected: true, exact: true }).evaluate((el) => el === document.activeElement), true, "sen terminalmontering stjeler ikke fokus fra faneraden");
  await page.keyboard.press("ArrowRight");
  await tabs.getByRole("tab", { name: "Diff", selected: true, exact: true }).waitFor();
  await h.api("PATCH", "/api/settings", { panelButtons: "separate" });
  await page.getByTestId("stack-panel-changes").waitFor();
  await page.getByRole("group", { name: "Panelknapper" }).getByRole("button", { name: "Diff", exact: true }).click();
  await panel.getByTestId("panel-home").filter({ visible: true }).waitFor();
  assert.equal(await panel.isVisible(), true, "topbar-lukk av siste stackpanel viser velgeren");
  await h.api("PATCH", "/api/settings", { panelButtons: "together" });
  assert.equal(await tabs.getByRole("tab", { name: "Diff", exact: true }).count(), 0, "lukket verktøy kommer ikke tilbake ved bytte til Samlet");
  await tabs.getByRole("tab", { name: "Terminal", exact: true }).waitFor();
});
