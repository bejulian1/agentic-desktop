import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import path from "node:path";
import { test } from "node:test";
import { startHarness, until } from "./helpers.ts";

test("køkontroller bevarer rekkefølge og vedlegg, synker endringer og flytter atomisk til usendt sidechat", async (t) => {
  const h = await startHarness(t);
  const project = await h.project(undefined, { permissionMode: "ask" });
  writeFileSync(path.join(project.path, "notat.txt"), "vedleggets opprinnelige innhold");
  const source = await h.thread(project.id);
  const other = await h.thread(project.id);
  await h.api("POST", `/api/threads/${source.id}/messages`, { text: "lag en side" });
  await until(async () => (await h.events(source.id)).some((e) => e.event.type === "approval.requested"), "avventer verktøygodkjenning");
  const first = await h.api("POST", `/api/threads/${source.id}/messages`, { text: "første melding", attachments: [{ kind: "file", path: "notat.txt" }] });
  const second = await h.api("POST", `/api/threads/${source.id}/messages`, { text: "andre melding" });
  writeFileSync(path.join(project.path, "notat.txt"), "nyere filinnhold");
  await h.api("PATCH", `/api/threads/${source.id}/queue/${first.messageId}`, { text: "/ny-kommando er bokstavelig tekst" });
  const jobs = h.app.store.queuedJobs<any>(source.id);
  assert.deepEqual(jobs.map((job) => job.id), [first.messageId, second.messageId]);
  assert.equal(jobs[0].kind, "message");
  assert.match(jobs[0].modelText, /^\/ny-kommando er bokstavelig tekst/);
  assert.match(jobs[0].modelText, /vedleggets opprinnelige innhold/);
  assert.doesNotMatch(jobs[0].modelText, /nyere filinnhold/);
  await assert.rejects(h.api("PATCH", `/api/threads/${source.id}/queue/${first.messageId}`, { text: " " }), /400/);
  await assert.rejects(h.api("PATCH", `/api/threads/${source.id}/queue/${first.messageId}`, { text: "ny", steer: true }), /400/);
  await assert.rejects(h.api("DELETE", `/api/threads/${other.id}/queue/${first.messageId}`), /404/);
  await h.api("PATCH", `/api/threads/${source.id}/queue/${first.messageId}`, { steer: true });
  const changed = (await h.events(source.id)).filter((e) => e.event.type === "user.queued" && e.event.messageId === first.messageId).at(-1)!;
  assert.equal(changed.event.type === "user.queued" && changed.event.steer, true);
  const moved = await h.api("POST", `/api/threads/${source.id}/queue/${first.messageId}/side-draft`, {});
  assert.equal(moved.text, "/ny-kommando er bokstavelig tekst");
  assert.equal(moved.attachments[0].path, "notat.txt");
  assert.equal(moved.thread.parentThreadId, source.id);
  assert.equal(moved.thread.origin, "user");
  assert.equal(moved.thread.projectId, project.id);
  assert.deepEqual(await h.events(moved.thread.id), [], "åpning starter ingen modell");
  assert.deepEqual((await h.api("GET", `/api/threads/${moved.thread.id}/queued-draft`)).draft, { text: moved.text, attachments: moved.attachments }, "utkastet kan gjenhentes selv om flyttesvaret mistes");
  assert.deepEqual(h.app.store.queuedJobs<any>(source.id).map((job) => job.id), [second.messageId]);
  const count = h.app.store.threads().length;
  await assert.rejects(h.api("POST", `/api/threads/${source.id}/queue/${first.messageId}/side-draft`, {}), /404/);
  assert.equal(h.app.store.threads().length, count, "ingen foreldreløs sidechat når meldingen har forlatt køen");
  const removed = await h.api("DELETE", `/api/threads/${source.id}/queue/${second.messageId}`);
  assert.equal(removed.text, "andre melding");
  assert.equal(h.app.store.hasQueued(source.id), false);
  assert.equal((await h.events(source.id)).filter((e) => e.event.type === "user.queue-removed").length, 2);
  await h.api("POST", `/api/threads/${moved.thread.id}/messages`, { text: "hjelp" });
  assert.equal((await h.api("GET", `/api/threads/${moved.thread.id}/queued-draft`)).draft, null, "en akseptert melding rydder det flyttede utkastet");
});
